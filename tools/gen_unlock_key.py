#!/usr/bin/env python3
"""
gen_unlock_key.py - create the secret key for advanced-mode unlock.

    ./tools/gen_unlock_key.py            # writes secrets/unlock_key.h + secrets/unlock_key.hex

- secrets/unlock_key.h   compiled into the firmware (picked up automatically)
- secrets/unlock_key.hex give to your app team (store in the app's secure
                         backend or obfuscated in the app; see docs/PROFILES_AND_UNLOCK.md)

Both files are git-ignored. Keep backups: if the key is lost, apps built
with it can't unlock controllers flashed with it. If it LEAKS, anyone can
unlock - rotate it in the next firmware release.
"""
import os
import pathlib
import secrets
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "secrets"
out.mkdir(exist_ok=True)
h, x = out / "unlock_key.h", out / "unlock_key.hex"
if (h.exists() or x.exists()) and "--force" not in sys.argv:
    sys.exit(f"{h} already exists. Use --force to replace it (old apps will stop working).")

key = secrets.token_bytes(32)
body = ", ".join(f"0x{b:02X}" for b in key)
h.write_text(
    "/* GENERATED by tools/gen_unlock_key.py - SECRET, do not commit. */\n"
    "#ifndef SK2V_UNLOCK_KEY_H\n#define SK2V_UNLOCK_KEY_H\n"
    f"#define SK2V_UNLOCK_KEY_BYTES {body}\n#endif\n")
x.write_text(key.hex() + "\n")
os.chmod(h, 0o600)
os.chmod(x, 0o600)
print(f"wrote {h}\nwrote {x}\nRebuild the firmware to use the new key.")
